// Codex への一括依頼（第3弾: キャラ以外 = 背景・地面/足場・アイコン・乗り物・タイトル）を書き出す
//   node tools/gen_codex_batch3.mjs → docs/art_handoff/CODEX_BATCH_03.md / CODEX_BATCH_03.csv
import { writeFileSync } from 'node:fs';
import { ITEMS } from '../src/data/items.js';
import { SKILLS } from '../src/data/skills.js';

const STYLE = 'ちびアニメ調のゲームと同じ絵柄、太めの濃い紫(#2A1430)の輪郭線、セル塗り2段＋ツヤ、ネオン×夕焼けの架空のリゾート都市「ヴァイス・ベイ」、全年齢向け、既存のゲームや実在の場所・ブランドに似せない、文字・ロゴは入れない';
const REG = {
  beach: ['ヴァイス・ビーチ', '夕焼けのビーチ。ヤシの木、カラフルな海の家・アイスクリーム屋・モーテル、桟橋、ネオンの看板', '砂浜と海、ヤシ林、ライフガードの見張り台、遠くの桟橋と観覧車'],
  downtown: ['ダウンタウン', 'ネオンの繁華街。ビル、ブティック、屋台、交差点の信号、ビルボード（文字なし）', '高架下・裏通り・駐車場、遠くの摩天楼'],
  slums: ['港のスラム', '港町のスラム。トタンの家、落書き（文字なし）、コンテナ、クレーン、裸電球', '倉庫街・コンテナヤード・錆びたクレーン・波止場'],
  swamp: ['霧のワニ沼', '沼のほとりの小さな集落。高床の小屋、ランタン、ボート小屋', '霧の沼地、マングローブ、朽ちた桟橋、ホタル'],
  casino: ['カジノ・ストリップ', '金と紫のカジノ街。豪華なホテル、噴水、ネオンのアーチ、レッドカーペット', 'カジノの裏手・豪華ホテルの庭園・ゴルフ場'],
  rooftop: ['摩天楼の屋上', '超高層ビルの屋上の街。ヘリポート、給水塔、空調機、ネオンのアンテナ', 'ビルの屋上が連なる空中の道、クレーン、遠くの街の灯り'],
  spaceport: ['宇宙港', '近未来の宇宙港の町。発着場、ドーム、ホログラム、整備中のシャトル', '発射台・宇宙港の外縁・月面のような岩場、遠くのロケット'],
};
const rows = [];
const add = (sec, file, size, title, prompt) => rows.push({ sec, file, size, title, prompt });

// ⑪ 背景
for (const [r, [name, town, field]] of Object.entries(REG)) {
  for (const [kind, desc] of [['town', town], ['field', field]]) {
    for (const [lay, ldesc] of [['far', '遠景（いちばん奥。空のすぐ手前の、かすんだシルエットの街並み・山・海。色は空になじむ淡い色）'], ['mid', '中景（建物・木・看板など。地面の線 y=640 に建物の足元をそろえる）']]) {
      add('⑪ 背景', `bg/${r}_${kind}_${lay}.png`, '2560×720',
        `${name}・${kind === 'town' ? '町' : 'フィールド'}・${lay === 'far' ? '遠景' : '中景'}`,
        `横スクロールゲームの背景のレイヤーを1枚描いてください。場所：${name}の${kind === 'town' ? '町の中' : '町の外のフィールド'}。内容：${desc}。レイヤー：${ldesc}。条件：横 2560×720、**空は描かず透明**（空はゲームが時間で塗る）、**左右の端がつながる（横に何枚並べても継ぎ目が無い）**、地面より下（y=640〜720）は${lay === 'mid' ? '地面の手前の縁（歩道・砂など）を少しだけ' : '透明'}、人物・車・文字は描かない。画風：${STYLE}`);
    }
    add('⑪ 背景', `bg/${r}_${kind}_lights.png`, '2560×720', `${name}・${kind === 'town' ? '町' : 'フィールド'}・夜のあかり`,
      `直前に描いた「${name}・${kind === 'town' ? '町' : 'フィールド'}・中景」と同じ 2560×720 に、**夜に光る部分だけ**（窓の明かり・ネオン看板の光・街灯・ランタン）を透明の上に描いてください。中景と重ねてぴったり合う位置に。光の色は明るく、建物そのものは描かない。ゲームが夜だけ加算合成で重ねます。`);
  }
}
// ⑫ 地面・足場
for (const [r, [name]] of Object.entries(REG)) {
  add('⑫ 地面・足場', `tiles/${r}_ground.png`, '512×256', `${name}の地面`, `横スクロールゲームの地面のタイルを1枚。場所：${name}。条件：512×256、**左右の端がつながる**、上端から40pxの線が歩く面（それより上は草・砂・縁石の出っ張りだけ、あとは透明）、断面は土・石・コンクリートなど場所に合う素材。画風：${STYLE}`);
  add('⑫ 地面・足場', `tiles/${r}_platform.png`, '512×96', `${name}の足場`, `横スクロールゲームの空中の足場（乗れる板）のタイルを1枚。場所：${name}（木の板・鉄骨・看板の上など場所に合う物）。条件：512×96、**左右の端がつながる**、上端から16pxの線が乗る面、下側は厚みと影、背景は透明。画風：${STYLE}`);
}
// ⑬ 装備アイコン（スタイルごと・基準色。ゲームが色を塗り替える）
const st = {};
for (const it of Object.values(ITEMS)) if (it.type === 'equip' && it.slot !== 'pet') { const k = it.slot + '/' + it.look.style; (st[k] = st[k] || []).push(it); }
const SLOT = { hat: '帽子', top: '上着', bottom: '下', shoes: '靴', accessory: 'アクセサリー', weapon: '武器' };
for (const [k, list] of Object.entries(st)) {
  const [slot, style] = k.split('/');
  const base = list[0];
  add('⑬ 装備アイコン', `icons/equip/${slot}_${style}.png`, '256×256', `${SLOT[slot]}：${base.name}など（${list.length}種）`,
    `ゲームのアイテム欄に出す装備のアイコンを1枚。物：${SLOT[slot]}「${list.map((i) => i.name).slice(0, 4).join('・')}」の共通の形（${style}）。色：主色 ${base.look.color}、差し色 ${base.look.accent}（ゲームが色違いに塗り替えるので、この色でくっきり塗る）。条件：256×256、透明背景、物だけを斜め上から見た形で中央に大きく（画面の8割）、人物や手は描かない、文字なし。画風：${STYLE}`);
}
// ⑭ 消耗品・素材アイコン（アイテムごと）
for (const it of Object.values(ITEMS)) if (it.type !== 'equip') {
  add('⑭ 消耗品・素材アイコン', `icons/item/${it.id}.png`, '256×256', it.name,
    `ゲームのアイテム欄に出すアイコンを1枚。物：「${it.name}」${it.desc ? '（' + it.desc + '）' : ''}。条件：256×256、透明背景、物だけを中央に大きく（画面の8割）、文字なし。画風：${STYLE}`);
}
// ⑮ スキルアイコン
const HERO = { luna: 'ストリートスター（スピード・銃・斬撃）', jin: 'ストリートブロウラー（パワー・格闘）', hacker: 'ストリートハッカー（電脳魔法）' };
for (const s of Object.values(SKILLS)) {
  add('⑮ スキルアイコン', `icons/skill/${s.id}.png`, '256×256', `${s.name}（${s.hero}）`,
    `ゲームのスキルのアイコンを1枚。スキル名：「${s.name}」${HERO[s.hero] ? '・' + HERO[s.hero] : ''}。効果：${s.desc || ''}。色の基調：${s.color || 'ネオン'}。条件：256×256、正方形いっぱいに描く絵（背景込み・角は丸めない。ゲームが枠を付ける）、技の印象が一目で分かるモチーフ（武器・光・エフェクト）、人物は小さめかシルエットまで、文字なし。画風：${STYLE}`);
}
// ⑯ 乗り物
for (const [k, n] of [['bike', 'ネオンのバイク（スクーター寄りのストリートバイク）'], ['sports', '真っ赤なスポーツカー（オープンカー）'], ['police', 'パトカー（白黒・屋根に赤青の回転灯）']]) {
  add('⑯ 乗り物', `vehicles/${k}.png`, '1024×512', n + 'の車体', `横スクロールゲームの乗り物を1枚。物：${n}。条件：1024×512、透明背景、**右向きの真横**、**タイヤは描かず**（タイヤの所は空ける）、**タイヤの中心にマゼンタ #FF00FF の小さな丸**を前後1つずつ描く（ゲームがそこにタイヤを付けて回す）、運転手は描かない、文字・ナンバーなし。画風：${STYLE}`);
  add('⑯ 乗り物', `vehicles/${k}_wheel.png`, '256×256', n + 'のタイヤ', `直前の${n}のタイヤを1つ。条件：256×256、透明背景、真横から見た円いタイヤとホイールを中央に、回しても不自然でない模様。画風：${STYLE}`);
}
// ⑰ タイトル・ワールドマップ
add('⑰ タイトル・地図', 'ui/title_art.png', '1920×1080', 'タイトル画面の絵', `ゲームのタイトル画面の背景イラスト。ネオンと夕焼けのリゾート都市ヴァイス・ベイを見下ろす構図、手前に主人公のルナ（添付の顔・髪・素体の絵と同じ見た目）・ジン・ハッカーが並ぶ。中央上はロゴを置くので空ける。文字なし。1920×1080。画風：${STYLE}`);
add('⑰ タイトル・地図', 'ui/logo.png', '1600×600', 'ロゴ「NEON VICE STORY」', '「NEON VICE STORY」のロゴ。ネオン管風の文字＋夕焼けのグラデーション、透明背景、1600×600。文字はこの3語だけ、正確な綴りで。');
add('⑰ タイトル・地図', 'ui/world_map.png', '2048×1152', 'ワールドマップの絵', `ゲームのワールドマップ（M キー）の背景になる、島の都市ヴァイス・ベイの鳥瞰イラスト。7つの地域（ビーチ・ダウンタウン・港のスラム・霧のワニ沼・カジノ街・摩天楼・宇宙港）を、添付のゲーム画面のワールドマップと同じ並びで描き分ける。文字・地名は入れない（ゲームが上に書く）。2048×1152。画風：${STYLE}`);

const secs = [...new Set(rows.map((r) => r.sec))];
const md = ['# Codex への一括依頼（第3弾）: キャラ以外の画像（背景・地面/足場・アイコン・乗り物・タイトル）', '',
  '**作業の続け方:**',
  '- 第2弾（`CODEX_BATCH_02.md`）が終わったら、そのまま続けてください。',
  '- 上の段から順に、1段ごと（⑪、⑫…）に ZIP で納品してください。',
  '- 自分で確認（大きさ・透明・継ぎ目・マゼンタの印）して合格したら、こちらの返事を待たずに次へ進んでください。',
  '- 大きな不具合で進められない段だけ止め、ほかは続けてください。',
  '', '**共通:**',
  '- 絵柄は第1弾と同じです（見本 `style/luna_f_reference.png`）。',
  '- 保存先は `assets/sprites/` の下、表のファイル名のとおりです。',
  '- 各ファイルの詳しい指示文は `CODEX_BATCH_03.csv` にあります（「AIへの指示文」の列）。',
  '', '**背景の重ね方（ゲーム側）:**',
  '- 空（ゲームが時間で塗る）の上に、遠景（ゆっくり動く）と中景（少し速く動く）を重ねます。',
  '- 夜は「あかり」を光らせて重ねます。',
  '- 横に繰り返して並べるので、**左右の端が必ずつながる**ように描いてください。',
  '- 中景の建物の足元は y=640 にそろえます。', '',
  `**合計: ${rows.length} 枚**`, ''];
for (const s of secs) {
  const rs = rows.filter((r) => r.sec === s);
  md.push(`## ${s}（${rs.length}枚）`, '', '| 保存先 | 大きさ | 内容 |', '|---|---|---|');
  for (const r of rs) md.push(`| \`${r.file}\` | ${r.size} | ${r.title} |`);
  md.push('');
}
writeFileSync('docs/art_handoff/CODEX_BATCH_03.md', md.join('\n'));
const esc = (v) => `"${String(v ?? '').replace(/"/g, '""')}"`;
writeFileSync('docs/art_handoff/CODEX_BATCH_03.csv', '﻿' + ['段,保存ファイル名（assets/sprites/ の下）,大きさ,内容,AIへの指示文'].concat(rows.map((r) => [r.sec, r.file, r.size, r.title, r.prompt].map(esc).join(','))).join('\r\n'));
console.log('CODEX_BATCH_03:', rows.length, '枚', secs.map((s) => s + ' ' + rows.filter((r) => r.sec === s).length).join(' / '));
