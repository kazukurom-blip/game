// 敵ごとに落とす書の種類を決める（ID から決まった順で 2 種類）
export function scrollsFor(mobId) {
  const n = parseInt(mobId.slice(1), 10);
  const a = SCROLLS[(n * 7) % SCROLLS.length][0];
  const b = SCROLLS[(n * 13 + 5) % SCROLLS.length][0];
  return a === b ? [a] : [a, b];
}
