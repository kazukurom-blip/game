/** マップの ID → 地域の雰囲気の組 */
export function areaOf(map) {
  const r = map[0];
  if (r === 'S') return 'island';
  if (r === 'C') return 'ceres';
  if (r === 'F') return 'hyoga';
  if (r === 'T') return 'tinkle';
  if (r === 'M') return 'marina';
  if (r === 'P') return 'temple';
  if (r === 'D') return 'dragon';
  if (r === 'H') return 'flame';
  if (r === 'E') return 'star';
  const n = Number(map.slice(1));
  if (n < 100) return 'market';
  if (n < 200) return 'port';
  if (n < 300) return 'pom';
  if (n < 400) return 'silva';
  if (n < 500) return 'gard';
  if (n < 600 || n >= 700) return 'crow';
  return 'nemu';
}

function roleOf(id, name, extra) {
  if (extra.travel || extra.taxi) return 'travel';
  if (name.startsWith('試験官')) return 'exam';
  if (name.startsWith('受付')) return 'reception';
  return 'folk';
}

const baseId = (id) => id.replace(/_[A-Z]\d{3}$/, '');

/**
 * NPC の一覧（npcs.mjs の NPCS）→ ID ごとのセリフ。
 * 専用が無い人は、地域の組を地域の中の順番でずらして 2 つ・役の組から 1 つ・育ち具合の組から 1 つ（同じ町の人で同じ文が並ばない）。
 */
export function buildNpcLines(npcs) {
  const out = {};
  const used = {};      // 地域 → 何人目
  const roleUsed = {};  // 地域・役 → 何人目
  let stage = 0;
  for (const [id, name, map, extra = {}] of npcs) {
    const own = LINES[id] || LINES[baseId(id)];
    if (own) { out[id] = own.slice(); continue; }
    const area = areaOf(map);
    const pool = AREA_POOL[area];
    const k = used[area] = (used[area] ?? -1) + 1;
    const lines = [];
    lines.push(STAGE_POOL[stage++ % STAGE_POOL.length]);
    const role = roleOf(id, name, extra);
    const rp = ROLE_POOL[role];
    if (rp.length) {
      const rk = roleUsed[area + role] = (roleUsed[area + role] ?? -1) + 1;
      lines.push(rp[rk % rp.length]);
    }
    for (let i = 0; i < 2; i++) lines.push(pool[(k * 2 + i) % pool.length]);
    out[id] = [...new Set(lines)];
  }
  return out;
}

/** 検査: 文の形・条件の書き方・同じ町で同じ文が並ばないか（専用のセリフどうしは除く）。問題の一覧を返す */
export function checkNpcLines(npcs, lines) {
  const problems = [];
  const COND = /^(lv|tier)(>=|<=|=|<|>)\d+$|^!?done=[A-Z0-9-]+$|^doing=[A-Z0-9-]+$|^line=(warrior|magician|bowman|thief|pirate)$/;
  const byArea = {};
  for (const [id, , map] of npcs) {
    const l = lines[id];
    if (!l || l.length < 3) { problems.push(`npc_lines: ${id} のセリフが 3 つより少ない`); continue; }
    for (const s of l) {
      if (typeof s !== 'string' || !s.trim()) problems.push(`npc_lines: ${id} に空の文`);
      const m = /^\[([^\]]*)\]/.exec(s);
      if (m) for (const c of m[1].split(',')) if (!COND.test(c.trim())) problems.push(`npc_lines: ${id} の条件「${c}」が読めない`);
      const text = s.replace(/^\[[^\]]*\]/, '');
      if (text.length > 40) problems.push(`npc_lines: ${id} の文が長い（${text.length} 字）: ${s}`);
    }
    if (LINES[id] || LINES[baseId(id)]) continue;
    const a = map; // 同じマップ（町）の中で
    for (const s of l) {
      if (s.startsWith('[')) continue;
      (byArea[a] ||= {})[s] = (byArea[a][s] || []).concat(id);
    }
  }
  for (const [a, m] of Object.entries(byArea)) for (const [s, ids] of Object.entries(m)) if (ids.length > 1) problems.push(`npc_lines: ${a} で ${ids.join('・')} が同じ文「${s}」`);
  return problems;
}
